  var lang = "en";

  function valid(l) { return LANGS.indexOf(l) >= 0; }

  // The raw entry (string or array) in the current language, English when it is missing.
  function raw(key) {
    var v = STRINGS[lang][key];
    return v === undefined ? STRINGS.en[key] : v;
  }

  // vars.n picks one/other and, like every other var, fills its {placeholder}. A var
  // named n may be given pre-formatted as vars.nText (thousands grouped).
  function t(key, vars) {
    var v = raw(key);
    if (v === undefined) return key;
    if (Array.isArray(v)) v = vars && vars.n === 1 ? v[0] : v[v.length - 1];
    if (!vars) return v;
    return String(v).replace(/\{(\w+)\}/g, function (m, name) {
      if (name === "n" && vars.nText != null) return vars.nText;
      return vars[name] != null ? String(vars[name]) : m;
    });
  }

  function list(key) { var v = raw(key); return Array.isArray(v) ? v : []; }

  // Language from a URL query (?lang=es) first, then the stored choice, else English.
  function pick(search, stored) {
    var m = /[?&]lang=([a-z]{2})\b/i.exec(search || "");
    if (m && valid(m[1].toLowerCase())) return m[1].toLowerCase();
    return valid(stored) ? stored : "en";
  }

  function setLang(l) { if (valid(l)) lang = l; return lang; }
  function getLang() { return lang; }

  // Static copy in the page: data-i18n (text), data-i18n-title, data-i18n-aria-label,
  // data-i18n-content (meta tags).
  function apply(doc) {
    doc = doc || (typeof document !== "undefined" ? document : null);
    if (!doc) return;
    doc.documentElement.lang = lang;
    var each = function (attr, fn) {
      doc.querySelectorAll("[" + attr + "]").forEach(function (el) { fn(el, t(el.getAttribute(attr))); });
    };
    each("data-i18n", function (el, s) { el.textContent = s; });
    each("data-i18n-title", function (el, s) { el.title = s; });
    each("data-i18n-aria-label", function (el, s) { el.setAttribute("aria-label", s); });
    each("data-i18n-content", function (el, s) { el.setAttribute("content", s); });
  }

  // In the browser: start in the chosen language (storage may be blocked: then English).
  if (typeof window !== "undefined") {
    var stored = null;
    try { stored = window.localStorage.getItem("latidos.lang"); } catch (e) { stored = null; }
    setLang(pick(window.location && window.location.search, stored));
    try { document.documentElement.lang = lang; } catch (e) {}
  }

  var api = { t: t, list: list, setLang: setLang, getLang: getLang, pick: pick, apply: apply,
              LANGS: LANGS, STRINGS: STRINGS };
  if (typeof module !== "undefined" && module.exports) module.exports = api;
  else root.LatidosI18n = api;
